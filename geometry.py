import math

# ค่าที่วัดจริงจากการจัดวาง (Task 5B) — ถ้าขยับฐานหรือล้อ ต้องวัดใหม่แล้วแก้ที่นี่
# ★ วัดถึง "ปลายจุ๊บ" ไม่ใช่หน้าล้อ — เพราะสูตรนี้คำนวณจุดที่แขนต้องไปแตะ
#   จุ๊บยื่นออกมาทางแขน ปลายจุ๊บจึงอยู่ใกล้แขนกว่าหน้าล้อหลายสิบ มม.
#   วัดผิดจุด = แขนหยุดก่อนถึง หรือดันเลยจุ๊บ (เฟสละเอียดแก้ให้ไม่ได้
#   เพราะมันแก้แค่ซ้าย-ขวากับบน-ล่าง ไม่แก้ระยะลึก)
X_WHEEL = 340.0   # ระยะแนวราบจากแกน J1 ถึง "ปลายจุ๊บ" (มม.) วัดจริง ±5 มม.
ZC_HUB = 80.0     # ความสูงดุมล้อจากแผ่นฐานแขน (มม.) — z=0 คือระดับแผ่นฐาน
R_VALVE = 150.0   # รัศมีจากดุมล้อถึงก้านจุ๊บ (มม.)


def valve_pose(clock: float) -> tuple[float, float, float]:
    """มุมนาฬิกา → (r, theta_deg, z) ตามสูตรใน DESIGN.md หัวข้อ 6.1

    clock : ตำแหน่งจุ๊บบนหน้าปัดล้อ รับทศนิยมได้ (6.5 = ระหว่าง 6 กับ 7 นาฬิกา)
            ★ นับจากมุมมองของกล้องที่มองเข้าหาหน้าล้อ (นิยามใน CONTEXT.md)

    คืน (r, theta_deg, z) ในระบบพิกัดทรงกระบอกที่ arm.move_to() รับ
    """
    # ⚠️ ต้องเป็น (6 - clock) ไม่ใช่ (clock - 6)
    # ถ้าสลับ จะได้ r กับ z ตรงเป๊ะทุกจุด แต่ theta กลับด้านหมด
    # แขนจะกวาดไปผิดข้างโดยที่ตัวเลขทุกตัวดูถูกต้อง — หาสาเหตุยากมาก
    phi = math.radians((6 - clock) * 30)

    y = R_VALVE * math.sin(phi)              # เยื้องซ้าย-ขวาจากแนวกลาง
    z = ZC_HUB - R_VALVE * math.cos(phi)     # 6 นาฬิกา = ต่ำสุด
    r = math.hypot(X_WHEEL, y)
    theta_deg = 90 + math.degrees(math.atan2(y, X_WHEEL))

    return r, theta_deg, z


if __name__ == '__main__':
    print(f"X={X_WHEEL:.0f} มม. · ZC={ZC_HUB:.0f} มม. · R={R_VALVE:.0f} มม.\n")
    print(f"{'นาฬิกา':>8} | {'r (มม.)':>9} | {'theta':>7} | {'z (มม.)':>9}")
    print('-' * 42)
    for c in [5, 5.5, 6, 6.5, 7, 7.5, 8, 8.5, 9]:
        r, th, z = valve_pose(c)
        print(f"{c:>8} | {r:>9.1f} | {th:>6.1f}° | {z:>9.1f}")
